#!/usr/bin/env python3
"""Generate the Chinese record of the BIP39 wordlist (main/kiss_zhwords_tab.c).

    gen_zh_words.py           write main/kiss_zhwords_tab.c and
                              tools/fonts/glyphs_zhwords.txt
    gen_zh_words.py --check   fail if either file is stale

The Chinese words are a RECORD of the English ones and nothing more. Index i of
the BIP39 Simplified Chinese list (chinese_simplified.txt, the copy libwally
vendors) stands for index i of the English list, so a Chinese paper backup
carries exactly the same 11 bit numbers as the English one. The seed is always
derived from the ENGLISH sentence: BIP39 feeds the mnemonic STRING to PBKDF2,
so the same entropy written in Chinese would open a different wallet, and that
is a wallet no coordinator this signer pairs with would ever find.

Pinyin comes from pypinyin (pip install pypinyin), toneless, with u-umlaut
written as v the way every pinyin keyboard types it ("lv" for 绿). Every
reading pypinyin knows is kept, primary first: an owner types the reading THEY
know, and a heteronym typed by its second reading must still be found. The
search in kiss_zhwords.c ranks primary readings first, so the extra readings
never push a common character down the candidate row.

The glyph list feeds tools/fonts/gen_fonts.sh, which subsets Source Han Sans
SC to exactly these 2048 characters (plus ASCII) for font_kiss_zhw*.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZH_LIST = os.path.join(ROOT, "components", "libwally-core", "upstream", "src",
                       "data", "wordlists", "chinese_simplified.txt")
EN_LIST = os.path.join(ROOT, "components", "libwally-core", "upstream", "src",
                       "data", "wordlists", "english.txt")
OUT_C = os.path.join(ROOT, "main", "kiss_zhwords_tab.c")
OUT_GLYPHS = os.path.join(ROOT, "tools", "fonts", "glyphs_zhwords.txt")


def read_list(path):
    with open(path, encoding="utf-8") as f:
        words = [w.strip() for w in f if w.strip()]
    if len(words) != 2048:
        sys.exit(f"FAIL: {path} has {len(words)} words, not 2048")
    return words


def readings(ch):
    from pypinyin import pinyin, Style
    got = pinyin(ch, style=Style.NORMAL, heteronym=True, v_to_u=False)[0]
    out = []
    for r in got:
        r = r.strip().lower()
        if not r or not r.isascii() or not r.isalpha():
            sys.exit(f"FAIL: {ch} has a reading that is not a-z: {r!r}")
        if r not in out:
            out.append(r)
        # lve/nve are typed lue/nue on most keyboards too; both find it.
        if r in ("lve", "nve"):
            alt = r.replace("v", "u")
            if alt not in out:
                out.append(alt)
    if not out:
        sys.exit(f"FAIL: pypinyin has no reading for {ch}")
    return out


def render():
    zh = read_list(ZH_LIST)
    en = read_list(EN_LIST)
    if len(set(zh)) != 2048:
        sys.exit("FAIL: the Chinese list repeats a character")
    for ch in zh:
        if len(ch) != 1 or len(ch.encode("utf-8")) != 3:
            sys.exit(f"FAIL: {ch!r} is not one 3 byte UTF-8 character")

    lines = [
        "// GENERATED by tools/gen_zh_words.py -- do not edit by hand.",
        "// Index i is the Chinese RECORD of English BIP39 word i. Never derive",
        "// a seed from these: see kiss_zhwords.h.",
        "#include \"kiss_zhwords.h\"",
        "",
        "// One character per index, UTF-8, three bytes each, no separators.",
        "const char kiss_zh_chars[KISS_ZH_WORDS * 3 + 1] =",
    ]
    for i in range(0, 2048, 32):
        chunk = "".join(zh[i:i + 32])
        lines.append(f"    \"{chunk}\"  // {i}")
    lines[-1] = lines[-1].replace("\"  //", "\";  //", 1)
    lines += [
        "",
        "// Toneless pinyin, readings separated by '|', the primary reading first.",
        "// Commented with the English word each index stands for.",
        "const char *const kiss_zh_pinyin[KISS_ZH_WORDS] = {",
    ]
    for i, ch in enumerate(zh):
        py = "|".join(readings(ch))
        lines.append(f"    \"{py}\",  // {i} {en[i]}")
    lines += ["};", ""]
    c_text = "\n".join(lines)
    # gen_fonts.sh passes this to lv_font_conv --symbols as is.
    glyph_text = "".join(sorted(set(zh))) + "\n"
    return c_text, glyph_text


def main():
    check = "--check" in sys.argv[1:]
    c_text, glyph_text = render()
    stale = []
    for path, text in ((OUT_C, c_text), (OUT_GLYPHS, glyph_text)):
        cur = None
        if os.path.exists(path):
            # Line endings are git's business (autocrlf on a Windows checkout),
            # not a sign the table is stale.
            with open(path, encoding="utf-8", newline="") as f:
                cur = f.read().replace("\r\n", "\n")
        if cur == text:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        sys.exit("FAIL: stale, run tools/gen_zh_words.py: " + ", ".join(stale))
    if check:
        print("OK: Chinese word tables are fresh")


if __name__ == "__main__":
    main()
