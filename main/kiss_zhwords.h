// Chinese BIP39 words as a RECORD of the English ones, and pinyin to find them.
//
// An owner may keep their backup in Chinese, type it back in pinyin, or open a
// sealed backup whose plaintext is a Chinese sentence. In every one of those
// the Chinese character is only a way of WRITING an index: character i of the
// BIP39 Simplified Chinese list is English word i, and the device turns it
// into the English word before anything else sees it.
//
// The seed is never derived from the Chinese. BIP39 hashes the mnemonic
// STRING, so 的的的...的 and abandon abandon ... about carry the same entropy
// and open two different wallets. Every coordinator this signer pairs with
// expects the English one, so English is the only sentence that ever reaches
// kiss_seed.c -- the conversions below are the whole of this module's contact
// with a seed.
//
// Pure, like kiss_lastword: no UI, no globals, host testable. The tables live
// in kiss_zhwords_tab.c, generated by tools/gen_zh_words.py.
#pragma once
#include <stddef.h>
#include <stdint.h>

#define KISS_ZH_WORDS 2048
#define KISS_ZH_PY_MAX 7     // longest reading is 6 letters ("zhuang")

// The generated tables. Prefer the accessors below.
extern const char kiss_zh_chars[KISS_ZH_WORDS * 3 + 1];
extern const char *const kiss_zh_pinyin[KISS_ZH_WORDS];

// The Chinese character for wordlist index 0..2047 as a NUL-terminated UTF-8
// string into out (4 bytes is enough). 0 on success, -1 out of range.
int kiss_zh_word(int index, char out[4]);

// The index of the one character at the start of s (UTF-8), or -1 when it is
// not on the list. *used, when given, gets the bytes it took (3), or 0.
int kiss_zh_index(const char *s, int *used);

// The primary toneless reading of index 0..2047 into out. 0 on success.
int kiss_zh_pinyin_primary(int index, char *out, size_t out_len);

// Every index whose pinyin matches `typed` (a-z, lower case), best first:
//   1. typed is the PRIMARY reading
//   2. typed is another reading
//   3. typed is a prefix of the primary reading
//   4. typed is a prefix of another reading
// Inside a rank, list order, which for this list is frequency order. Each
// index appears once. Skips the first `skip` matches and writes up to n
// indices to out; returns how many it wrote. Pass n = 0 to count them all.
int kiss_zh_suggest(const char *typed, int skip, uint16_t *out, int n);

// A Chinese mnemonic -> the English one. Characters may be separated by
// spaces (ASCII or U+3000) or run together. Fails (-1, out cleared) on any
// character off the list or a count other than 12, 15, 18, 21 or 24. The
// result is NOT checksum validated; kiss_seed_validate decides that.
int kiss_zh_to_english(const char *zh, char *out, size_t out_len);

// An English mnemonic -> the Chinese record, one space between characters.
// -1 (out cleared) on a word that is not an English BIP39 word.
int kiss_zh_from_english(const char *en, char *out, size_t out_len);

// 1 when s holds any byte >= 0x80: what tells a sealed Chinese sentence from
// an English one before either is validated.
int kiss_zh_looks_chinese(const char *s, size_t len);
